import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const out = resolve(root, ".output/journey-contract");
mkdirSync(out, { recursive: true });
execFileSync(process.execPath, [resolve(root, "node_modules/typescript/bin/tsc"), "src/lib/journey.ts", "--target", "ES2020", "--module", "ES2020", "--moduleResolution", "bundler", "--outDir", out, "--skipLibCheck", "--esModuleInterop"], { cwd: root, stdio: "inherit" });
const { parseJourney, moneyRange, selectJourney } = await import(pathToFileURL(resolve(out, "journey.js")).href);
// 与 Java 黄金测试生成的真实契约对接；先运行 mcp-server 测试，避免两份手写 schema 自说自话。
const raw = readFileSync(resolve(root, "../mcp-server/target/journey-ui-fixture.json"), "utf8");
const plan = parseJourney(raw);
assert(plan, "Java v3 result should parse");
assert.equal(moneyRange(null, null), "待核实");
assert(!moneyRange(null, null).includes("0"));
assert.equal(moneyRange(1000, 1000), "¥10");
assert.equal(parseJourney('{"schemaVersion":"trip-plan.v1"}'), null);
const wrong = JSON.parse(raw);
const unknown = wrong.options[0].cost.items.find((item) => item.status === "UNKNOWN");
unknown.minMinor = 0; unknown.maxMinor = 0;
assert.equal(parseJourney(JSON.stringify(wrong)), null, "unknown fee cannot be rendered as free");
assert.equal(selectJourney(plan.options, "cheapest"), undefined, "unknown fees cannot win cheapest");
assert.equal(selectJourney(plan.options, "fastest"), undefined, "unknown return cannot be guaranteed feasible");
const confirmed = structuredClone(plan.options[0]);
confirmed.feasibility = "FEASIBLE"; confirmed.returnJourney.status = "NOT_REQUESTED";
confirmed.cost.unknownCategories = []; confirmed.cost.maxTotalMinor = 10000;
const impossible = structuredClone(confirmed); impossible.id = "impossible"; impossible.feasibility = "INFEASIBLE"; impossible.travelMinutes = 1;
assert.equal(selectJourney([impossible, confirmed], "fastest").id, confirmed.id);
console.log("Journey v3: Java/TS contract, null money, cheapest exclusion and feasibility checks passed");
